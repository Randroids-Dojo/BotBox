import type { BotCard, Loadout, WeightClass } from '../contract';

export type AiStyle =
  /** Charges in, weapon first. */
  | 'aggressive'
  /** Circles, waits for an opening, backs off when hurt. */
  | 'tactical'
  /** Shoves the opponent toward hazards and walls. */
  | 'bully'
  /** Spins up, then hunts with the weapon edge. */
  | 'spinner'
  /** Tries to get under and fire or lift. */
  | 'wedger';

export interface Rival {
  id: string;
  card: BotCard;
  loadout: Loadout;
  style: AiStyle;
  /** 0..1 driving skill. */
  skill: number;
  /** 1 is the top seed. */
  seed: number;
}

function rival(
  id: string,
  card: Omit<BotCard, 'voiceId'>,
  loadout: Omit<Loadout, 'name'>,
  style: AiStyle,
  skill: number,
  seed: number,
): Rival {
  return { id, card: { ...card, voiceId: id }, loadout: { ...loadout, name: card.name }, style, skill, seed };
}

