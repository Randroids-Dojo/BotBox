export function rivalsFor(cls: WeightClass): Rival[] {
  return ROSTER.filter((r) => r.loadout.cls === cls).sort((a, b) => a.seed - b.seed);
}

export function rivalById(id: string): Rival | undefined {
  return ROSTER.find((r) => r.id === id);
}

